/*
 # Заявки: поле «откуда пришла»

 Учёт заявок ведётся на сайте: таблица `enrollments` — журнал, а переписка
 остаётся в MAX (личные сообщения никто никуда не переносит). Чтобы журнал был
 полезным, нужно отличать заявку с формы (источник `site`) от той, что человек
 написал в MAX или позвонил, — такие заводят в админке вручную.

 1. Изменения
 - `enrollments.source` (text, NOT NULL, default 'site') — site | max | phone | vk.
 - Индекс по source: считать «сколько пришло из MAX» приходится часто.

 2. Совместимость
 Код не падает, если миграция ещё не выполнена: админская вставка пробует
 записать source, при «column source does not exist» повторяет без него и
 кладёт метку в начало `comment` ([MAX] ...). Интерфейс читает источник так:
 row.source ?? метка в comment ?? 'site'. После выполнения миграции новые
 записи получают нормальное поле, старые остаются 'site' — это верно: других
 источников до админского ввода не было.
 7. Отдельно, чтобы не искать потом
 Живая таблица разошлась с 20260910200844_create_enrollments_table.sql: в том
 файле contact NOT NULL, а в базе есть phone и interest_label. Эта миграция
 расхождение не лечит — если придётся поднимать базу с нуля, сверьте схему и
 допишите отдельную миграцию, иначе форма заявок не сможет писать.
*/

ALTER TABLE enrollments ADD COLUMN IF NOT EXISTS source text NOT NULL DEFAULT 'site';

COMMENT ON COLUMN enrollments.source IS 'Канал поступления заявки: site (форма), max (сообщение в MAX), phone (звонок), vk (сообщение ВК)';

CREATE INDEX IF NOT EXISTS enrollments_source_idx ON enrollments (source);
